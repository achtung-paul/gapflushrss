# Alembic's migration runner for the project-scoped schema (Commodity
# and everything under it -- see db/project_base.py). This is a second,
# separate chain from alembic/env.py's central chain: this one has no
# single fixed database, it runs against whichever Postgres service
# you point it at (a Project's assigned PostgresService row, see
# core/service_db.py), and tracks its own migration history in a
# `alembic_version_project` table so it doesn't collide with the
# central chain's `alembic_version` table when both happen to point at
# the same physical database (true for the "Default" service created by
# the one-time adoption migration, see
# alembic/versions/<adoption migration>.py).

from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

from app.db.project_base import ProjectBase

# Import models so ProjectBase.metadata knows about every project-scoped
# table before Alembic compares it against the database (needed for
# --autogenerate). Central models get imported too (harmless -- they're
# registered on Base.metadata, which this chain never looks at).
import app.models  # noqa: F401

config = context.config

# Resolve the target database URL. Unlike the central chain, there's no
# settings-derived default -- this has to be supplied by whoever's
# running it:
#   1. Set directly on the Config object before this file runs, which is
#      how core/service_db.py's initialize_schema() drives it
#      programmatically for a specific service.
#   2. -x db_url=... on the command line, for the manual
#      "generate a migration inside the container" workflow (see
#      CLAUDE.md) -- normally pointed at the Default service so new
#      migrations get autogenerated against real, already-adopted
#      tables.
x_args = context.get_x_argument(as_dictionary=True)
url = config.get_main_option("sqlalchemy.url") or x_args.get("db_url")
if not url:
    raise RuntimeError(
        "alembic_project has no target database -- pass -x db_url=... "
        "or set it on the Config object before running migrations."
    )
config.set_main_option("sqlalchemy.url", url)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = ProjectBase.metadata
VERSION_TABLE = "alembic_version_project"


def run_migrations_offline():
    context.configure(
        url=url,
        target_metadata=target_metadata,
        version_table=VERSION_TABLE,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online():
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata, version_table=VERSION_TABLE)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
